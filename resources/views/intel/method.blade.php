        <h2>Current, out of date, not available</h2>
        <p>Every series has a window in which a reading is still current: a day for an exchange rate, a few weeks for a monthly index, over two years for an annual national statistic. A reading older than its window is shown as out of date, with its date, and is never presented as the latest. A series we hold nothing for is shown as not available. Colour is never the only signal: the three states differ in shape as well.</p>

        <h2>Where a figure comes from</h2>
        <p>Open "Show working" under any figure to see what it measures, its unit, its source, the period it describes, when we collected it, its licence, any limits the source states, and every value we hold. Revisions are kept, so a figure that changed shows what it was and when it changed. You can download the values as CSV with the credit line attached.</p>

        <h2>What we publish, and what we leave out</h2>
        <p>We publish a source only when its licence lets us do so on a site that may earn money. Where a licence is silent or limits use to non-commercial reading, we do not collect or show it, and the sources page lists what we are waiting on and why. We link to original reporting and do not copy it. We do not summarise text that we have no right to summarise.</p>

        <h2>How a question is answered</h2>
        <p>The search box reads your words for a place, an industry and a measure, and looks them up in stored figures. The answer is a template filled from those figures, so it can only repeat what a source said. If the figures that would answer the question are not held, the answer says so and lists what is missing. A model never writes an answer.</p>

        <h2>How developments are filed</h2>
        <p>An item is filed under an industry or a country by words in its headline and summary, from lists in our code. A matching word is not a judgement, and an item with no match is simply unfiled.</p>

